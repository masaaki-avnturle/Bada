# ---------------- Assembly ----------------
def assemble_document(input_text: str) -> str:
    title = "On a Network of Formal Relations: from Gamma to Zeta"
    author = "Auto-generated by omega-proof-gen.py"
    lines: List[str] = []
    lines.extend(make_preamble(title, author))

    # Intro
    lines.append("\\section{Introduction}")
    lines.append(tex_escape(input_text))
    lines.append("")
    # Stage: Gamma
    lines.append("\\section{Special Functions: Gamma and Related Integrals}")
    lines.extend(gen_gamma_nodes(NODES["gamma"]))
    lines.append("")

    # Stage: Shannon
    lines.append("\\section{Information-Theoretic Fragments}")
    lines.extend(gen_shannon_nodes(NODES["shannon"]))
    lines.append("")

    # Stage: Noncommutative Varieties
    lines.append("\\section{Noncommutative Algebraic Varieties and Cohomology}")
    lines.extend(gen_noncommutative_variety(NODES["noncomm_var"]))
    lines.append("")

    # Stage: Global differential manifolds
    lines.append("\\section{Global Differential Manifolds and Integration}")
    lines.extend(gen_global_diff(NODES["global_diff"]))
    lines.append("")

    # Stage: Gravity/Higgs
    lines.append("\\section{Field-Theoretic Sketches: Gravity and Higgs}")
    lines.extend(gen_gravity_higgs(NODES["gravity_higgs"]))
    lines.append("")

    # Stage: AGM / mean relations
    lines.append("\\section{Arithmetic--Geometric Mean and Elliptic Links}")
    lines.extend(gen_agm_nodes(NODES["agm"]))
    lines.append("")

    # Stage: Quantization
    lines.append("\\section{Quantization Perspectives}")
    lines.extend(gen_quantization_nodes(NODES["quantization"]))
    lines.append("")

    # Stage: Zeta
    lines.append("\\section{Zeta Functions and Spectral Regularization}")
    lines.extend(gen_zeta_nodes(NODES["zeta"]))
    lines.append("")

    # Theorem / Conjecture examples (synthetic, labeled)
    lines.append("\\section{Synthetic Theorems and Conjectures}")
    # produce a few numbered theorem-like statements that reference earlier sections
    lines.append("\\begin{theorem}[Spectral Regularity (synthetic)]")
    lines.append("Let $A$ be a positive elliptic operator on a closed manifold $M$. "
                 "Then the spectral zeta function $\\zeta_A(s)$ admits a meromorphic continuation "
                 "to $\\mathbb{C}$ with possible simple poles related to heat-kernel coefficients.")
    lines.append("\\end{theorem}")
    lines.append("")

    lines.append("\\begin{conjecture}[Gamma--Zeta Correspondence (synthetic)]")
    lines.append("There exists a formal correspondence assigning to certain Gamma-type integral transforms "
                 "a family of spectral zeta functions whose special values encode global arithmetic invariants.")
    lines.append("\\end{conjecture}")
    lines.append("")

    # Proof sketches
    lines.append("\\section{Proof sketches and heuristic links}")
    lines.append("We summarize informal derivations which connect integral representations, "
                 "index-like traces, and entropy/functional determinants:")
    lines.append("\\begin{itemize}")
    lines.append("\\item Use Mellin transforms of heat kernels to relate Gamma factors and spectral zeta functions.")
    lines.append("\\item Interpret Shannon relative entropy in continuum limits as a regularized trace.")
    lines.append("\\item Apply deformation quantization to pass from commutative geometric invariants to spectral invariants.")
    lines.append("\\end{itemize}")
    lines.append("")

    # Network appendix: produce many small symbolic relations to simulate a network
    lines.append("\\appendix")
    lines.append("\\section{Symbolic relation network (auto-generated)}")
    for i in range(1, 1 + sum(NODES.values())):
        # combine symbols randomly but in consistent LaTeX form
        a = random.choice(["\\Gamma(s)", "\\zeta(s)", "\\det\\Delta", "\\mathrm{Tr}(e^{-t\\Delta})", "\\mathcal{A}", "\\star"])
        b = random.choice(["\\Gamma(1-s)", "\\zeta'(0)", "H(P)", "\\mathrm{Res}", "\\nabla", "\\phi"])
        lines.append(f"\\paragraph{{Node {i}}} Relation example: $ {a} \\sim {b} + O(\\hbar)$.")
    lines.append("")

    # Closing remarks
    lines.append("\\section{Concluding remarks}")
    lines.append("The above expressions and fragments are intended as a scaffold for a more detailed,"
                 " formal treatment. Individual statements are synthetic and should be validated in"
                 " rigorous settings.")
    lines.append("")
    lines.append("\\end{document}")
    return "\n".join(lines)

# ---------------- Main CLI ----------------
def try_compile_pdf(tex_path: str) -> bool:
    # Attempt to run pdflatex twice for crossrefs; ignore if not present.
    try:
        cmd = ["pdflatex", "-interaction=nonstopmode", tex_path]
        # run twice
        subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=True)
        subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=True)
        return True
    except Exception:
        return False

def main(argv: List[str] | None = None) -> int:
    if argv is None:
        argv = sys.argv[1:]
    if not (1 <= len(argv) <= 2):
        print(USAGE, file=sys.stderr)
        return 2
    if len(argv) == 1:
        input_path = None
        out_tex = argv[0]
    else:
        input_path, out_tex = argv

    input_text = read_input(input_path)
    tex = assemble_document(input_text)
    try:
        with open(out_tex, "w", encoding="utf-8") as f:
            f.write(tex)
    except Exception as e:
        print(f"Error writing {out_tex}: {e}", file=sys.stderr)
        return 1

    print(f"Wrote LaTeX to {out_tex}")
    # attempt compilation
    compiled = try_compile_pdf(out_tex)
    if compiled:
        pdf_name = os.path.splitext(out_tex)[0] + ".pdf"
        if os.path.exists(pdf_name):
            print(f"Successfully compiled PDF: {pdf_name}")
        else:
            print("pdflatex reported success but PDF not found.", file=sys.stderr)
    else:
        print("pdflatex not available or compilation failed; .tex produced.", file=sys.stderr)
    return 0

if __name__ == "__main__":
    sys.exit(main())
