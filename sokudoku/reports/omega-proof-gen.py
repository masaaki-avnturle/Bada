from typing import List, Optional

# ---------------- Configuration ----------------
SEED = 12345
random.seed(SEED)

DEFAULT_INPUT_TEXT = (
    "Generate an expository-style manuscript connecting special functions, "
    "information-theoretic formulas, algebraic and differential geometry, "
    "field equations, arithmetic-analytic mean relations, quantization, and zeta functions."
)

# How many formula "nodes" to generate in each conceptual stage
NODES = {
    "gamma": 3,
    "shannon": 2,
    "noncomm_var": 3,
    "global_diff": 4,
    "gravity_higgs": 4,
    "agm": 3,
    "quantization": 4,
    "zeta": 3,
}

# Output names
