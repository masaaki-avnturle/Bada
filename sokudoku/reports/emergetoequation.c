					      static int ensure_dir(const char *path) {
    if (!path) return -1;
    struct stat st;
    if (stat(path, &st) == 0) return S_ISDIR(st.st_mode) ? 0 : -1;
    if (mkdir(path, 0755) == 0) return 0;
    if (errno == ENOENT) {
      char tmp[4096];
      strncpy(tmp, path, sizeof(tmp)-1);
      tmp[sizeof(tmp)-1] = 0;
      char *p = strrchr(tmp, '/');
      if (p && p != tmp) {
	*p = 0;
	if (ensure_dir(tmp) == 0) return mkdir(path, 0755) == 0 ? 0 : -1;
      }
    }
    return -1;
  }

					      static int write_file_mode(const char *path, const char *data, mode_t mode) {
						FILE *f = fopen(path, "wb");
						if (!f) {
						  fprintf(stderr, "open %s: %s\n", path, strerror(errno));
						  return -1;
						}
						if (fputs(data, f) == EOF) { fclose(f); return -1; }
						fclose(f);
						if (mode) chmod(path, mode);
						return 0;
					      }

					      static int write_path(const char *root, const char *rel, const char *data, mode_t mode) {
						char full[4096];
						snprintf(full, sizeof(full), "%s/%s", root, rel);
						char dir[4096];
						strncpy(dir, full, sizeof(dir)-1);
						dir[sizeof(dir)-1] = 0;
						char *p = strrchr(dir, '/');
						if (p) { *p = 0; ensure_dir(dir); }
						return write_file_mode(full, data, mode);
					      }

