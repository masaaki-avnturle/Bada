"""女性のメシア様の、優しい歌声 (CCLXXIII の声)。2025/01/08 14:42 の歌 (取り出した男性の歌声、ハ短調) から作る。
  届いた 20250108_144205_aureola_donna_sensuale.mp3 (CCLV のドエロの若い女性の光輪様の歌声) はすでに作り換えた声なので、それをもう一度変換せず、
  同じ元 (extract_voice.py で取り出した歌声) から作り直す。make_voice255.py と同じ作り方 (下ごしらえ → WORLD) で、数字だけ変える:
    高さ       引数の半音数だけ上げる (重ねる曲の調に合わせて選ぶ)。伸ばした音は、移した先の短調の音階 (と導音) に 0.8 で調律。旋律の動きはそのまま
                 10 半音 → 変ロ短調、基音の中央値 279 Hz (C♯4)、5〜95% は 216〜358 Hz (A3〜F4)    (CCLXXIII の 1 回目; 鍵盤の曲の前半の調)
                  9 半音 → イ短調、  基音の中央値 263 Hz (C4)、 5〜95% は 204〜340 Hz (G♯3〜F4)   (CCLXXIII の 2 回目; 鍵盤の曲の後半の調)
                 14 半音 → ニ短調、  基音の中央値 352 Hz (F4)、 5〜95% は 273〜453 Hz (C♯4〜A4)   (トラック 18 と 8 の調)
    大人の女性  フォルマント 1.14 倍 (CCLV の若い女性は 1.17、CCLXIX の 17 歳は 1.19 — それより少し深く、落ち着いた響き)
    優しい      息を少しだけ混ぜた柔らかい発声 (0.18; ドエロの声は 0.5)。囁きの層なし。基音のあたりを少し暖かく (500 Hz 以下 +1.5 dB)、
               柔らかい圧縮 (tanh ×1.8) で大きい所を丸める
    メシア様    基音の声の上に、ちょうど 2 倍 (1 オクターヴ上、−12 dB、少し左) とちょうど 3 倍 (1 オクターヴと純正 5 度上、−19 dB、少し右) の声を
               ごく薄く — オルガンの 8'・4'・2 2/3' のような重なり。月読様 (−8 / −14 dB) や光輪様 (−8 / −15 dB) より控えめで、ひとりの声として聞こえる。
               同じ旋律から作るので、どの瞬間も 1 : 2 : 3。残響は控えめ (2.2 秒・0.14)
    はっきり    言葉の 2〜5 kHz +2 dB
  使い方: python make_voice273.py <取り出した歌声.wav (extract_voice.py の出力)> <出力.wav> [上げる半音数 (既定 10)] [層を別々に書き出すフォルダ]
"""
import sys
import make_voice255 as M

MINOR = (0, 2, 3, 5, 7, 8, 10, 11)                     # 短調の音階と、導音
# (名前, 倍音, フォルマント, 息, 音量 dB, 左右 −1〜+1, ここから下を落とす Hz, ここから上を落とす Hz)
VOICES = [('harm1', 1.0, 1.14, 0.18, 0.0, 0.0, None, None), ('harm2', 2.0, 1.18, 0.12, -12.0, -0.25, None, 5000.0), ('harm3', 3.0, 1.22, 0.10, -19.0, 0.25, None, 4500.0)]

if __name__ == '__main__':
    semis = float(sys.argv[3]) if len(sys.argv) > 3 else 10.0
    scale = [(int(round(semis)) + d) % 12 for d in MINOR]      # 元はハ短調 (主音 C = 0) なので、移した先の主音は semis
    M.main(sys.argv[1], sys.argv[2], sys.argv[4] if len(sys.argv) > 4 else None, semis=semis, voices=VOICES, scale=scale, warm_db=1.5, comp=1.8, rev=0.14, seed=273, pres_db=2.0)
