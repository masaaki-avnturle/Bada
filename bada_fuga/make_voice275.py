"""女性のメシア様の、優しい話し声 (CCLXXV の声)。届いた 20261108_145525_aureola_sensuale_calma.mp3 から作る。
  元: calma の声は、11/08 14:55 の声をすでに作り換えたもの (215 Hz の少し低めの女声、5 度上と 1 オクターヴ上の声、息と囁き、残響)。
      11/08 14:55 の元の録音は手元に無いので、この音声から作り直す。読み取りと下ごしらえは make_voice265.py と同じ
      (Harvest で 120〜450 Hz の中だけを読む、読み落としを結ぶ、句の終わりを息に溶かす、低い所を抑える、息を減らす、残響を抑える、静かな話し始めを均す)。
  声の作りは make_voice273.py (メシア様の歌声) に合わせて、数字だけ変える:
    高さ       基音の中央値を引数の高さへ (重ねる曲の調に合わせて選ぶ)。伸ばした音は引数の長調の音階に 0.9 で調律
                 207.65 Hz (A♭3)・変ニ長調  — CCLXXV の 1 回目 (鍵盤の曲の前半; A♭ は変ニ長調の属音)
                 196.00 Hz (G3)・ハ長調     — CCLXXV の 2 回目 (鍵盤の曲の後半; G はハ長調の属音)
               17 歳の声 (B♭3 = 233 Hz) や 20 代の声 (A3 = 220 Hz) より低い、落ち着いた大人の女性の話し声の高さ
    大人の女性  フォルマント 1.035 倍 (元の 1.10 倍と合わせて 1.14 倍 — メシア様の歌声と同じ)
    優しい      抑揚 0.9 倍 (落ち着き)、息は減らしたまま少しだけ、250 Hz 以下 +1.5 dB (暖かさ)、柔らかい圧縮
    メシア様    基音の声の上に、ちょうど 2 倍 (−12 dB、少し左) とちょうど 3 倍 (−19 dB、少し右) の声をごく薄く — メシア様の歌声と同じ重なり。
               同じ抑揚から作るので、どの瞬間も 1 : 2 : 3。残響は控えめ (1.6 秒・0.12)
  使い方: python make_voice275.py <calma の声.wav (モノラル)> <出力.wav> [基音の中央値 Hz (既定 207.65)] [長調の主音 (0 = C … 11 = B; 既定 1 = D♭)] [層を別々に書き出すフォルダ]
"""
import sys
import make_voice265 as M

MAJOR = (0, 2, 4, 5, 7, 9, 11)

if __name__ == '__main__':
    M.TARGET = float(sys.argv[3]) if len(sys.argv) > 3 else 207.65
    tonic = int(sys.argv[4]) if len(sys.argv) > 4 else 1
    M.SCALE = [(tonic + d) % 12 for d in MAJOR]
    # (名前, 倍音, フォルマント, 音量 dB, 左右 −1〜+1, ここから上を落とす Hz)
    M.VOICES = [('harm1', 1.0, 1.035, 0.0, 0.0, None), ('harm2', 2.0, 1.07, -12.0, -0.25, 6000.0), ('harm3', 3.0, 1.105, -19.0, 0.25, 5000.0)]
    M.REV = 0.12
    M.main(sys.argv[1], sys.argv[2], sys.argv[5] if len(sys.argv) > 5 else None)
