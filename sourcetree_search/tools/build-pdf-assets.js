/*
 * build-pdf-assets.js — 同梱 PDF ライブラリ (app/www/vendor) を pdfjs-dist / pdf-lib から作り直す
 *   npm install pdfjs-dist@3.11.174 pdf-lib@1.17.1     (どこか作業用のフォルダで)
 *   node sourcetree_search/tools/build-pdf-assets.js <その node_modules のパス>
 *
 * pdf.js は日本語 PDF (CID フォント) の描画に CMap、非埋め込みの欧文フォントの描画に
 * 標準フォントのデータを必要とし、通常は fetch / XHR で個別に取りに行きます。しかし
 * EXE (file://) や HTML をダブルクリックで開いた場合はそれがブロックされ、日本語が
 * 表示されません。そこで全ファイルを base64 で 1 本の JS にまとめ、<script> で読める
 * ようにします (pdfview.js が独自の CMapReaderFactory / StandardFontDataFactory で供給)。
 */
"use strict";
var fs = require("fs"), path = require("path");
var nm = process.argv[2];
if (!nm || !fs.existsSync(path.join(nm, "pdfjs-dist"))) {
  console.error("usage: node build-pdf-assets.js <node_modules containing pdfjs-dist and pdf-lib>");
  process.exit(1);
}
var OUT = path.join(__dirname, "..", "app", "www", "vendor");
var pj = path.join(nm, "pdfjs-dist"), pl = path.join(nm, "pdf-lib");
fs.mkdirSync(path.join(OUT, "pdfjs"), { recursive: true });
fs.mkdirSync(path.join(OUT, "pdf-lib"), { recursive: true });

function copy(from, to) { fs.copyFileSync(from, to); console.log("copied  " + path.relative(OUT, to)); }
function bundle(dir, filter, globalName, outFile, note) {
  var names = fs.readdirSync(dir).filter(filter).sort(), parts = [], bytes = 0;
  names.forEach(function (n) {
    var buf = fs.readFileSync(path.join(dir, n));
    bytes += buf.length;
    parts.push(JSON.stringify(n) + ":" + JSON.stringify(buf.toString("base64")));
  });
  var js = "/* " + note + " — generated by tools/build-pdf-assets.js from pdfjs-dist " + ver + ". Do not edit. */\n" +
           "(function(g){g." + globalName + "={\n" + parts.join(",\n") + "\n};})(typeof globalThis!==\"undefined\"?globalThis:this);\n";
  fs.writeFileSync(outFile, js);
  console.log("bundled " + path.relative(OUT, outFile) + "  (" + names.length + " files, " + bytes + " bytes)");
}

var ver = JSON.parse(fs.readFileSync(path.join(pj, "package.json"), "utf8")).version;
copy(path.join(pj, "build", "pdf.min.js"), path.join(OUT, "pdfjs", "pdf.min.js"));
copy(path.join(pj, "build", "pdf.worker.min.js"), path.join(OUT, "pdfjs", "pdf.worker.min.js"));
copy(path.join(pj, "LICENSE"), path.join(OUT, "pdfjs", "LICENSE"));
copy(path.join(pj, "cmaps", "LICENSE"), path.join(OUT, "pdfjs", "LICENSE_CMAPS"));
copy(path.join(pj, "standard_fonts", "LICENSE_FOXIT"), path.join(OUT, "pdfjs", "LICENSE_FOXIT"));
copy(path.join(pj, "standard_fonts", "LICENSE_LIBERATION"), path.join(OUT, "pdfjs", "LICENSE_LIBERATION"));
bundle(path.join(pj, "cmaps"), function (n) { return /\.bcmap$/.test(n); }, "BADA_PDF_CMAPS",
       path.join(OUT, "pdfjs", "cmaps.bundle.js"), "Adobe CMap resources (bcmap) for pdf.js");
bundle(path.join(pj, "standard_fonts"), function (n) { return /\.(pfb|ttf)$/.test(n); }, "BADA_PDF_FONTS",
       path.join(OUT, "pdfjs", "standard_fonts.bundle.js"), "Standard 14 font data (Foxit / Liberation) for pdf.js");
copy(path.join(pl, "dist", "pdf-lib.min.js"), path.join(OUT, "pdf-lib", "pdf-lib.min.js"));
copy(path.join(pl, "LICENSE.md"), path.join(OUT, "pdf-lib", "LICENSE.md"));
fs.writeFileSync(path.join(OUT, "README.md"),
  "# vendor — 同梱ライブラリ (BadaCineVim の PDF 表示・編集用)\n\n" +
  "| ライブラリ | 版 | ライセンス | 用途 |\n|:--|:--|:--|:--|\n" +
  "| [pdf.js](https://github.com/mozilla/pdf.js) (`pdfjs/`) | " + ver + " | Apache-2.0 | PDF をページとして描画 |\n" +
  "| [pdf-lib](https://github.com/Hopding/pdf-lib) (`pdf-lib/`) | " +
  JSON.parse(fs.readFileSync(path.join(pl, "package.json"), "utf8")).version + " | MIT | 注釈を PDF に書き込む |\n\n" +
  "`pdfjs/cmaps.bundle.js` と `pdfjs/standard_fonts.bundle.js` は、pdf.js 付属の CMap / 標準フォントを\n" +
  "`file://` でも読めるよう 1 本の JS にまとめたものです (`tools/build-pdf-assets.js` で再生成)。\n\n" +
  "pdf.js " + ver + " には、フォント経由で任意の JavaScript が実行される脆弱性 (CVE-2024-4367) があります。\n" +
  "`pdfview.js` は公式の回避策どおり **`isEvalSupported: false`** で開くため、この経路は無効です\n" +
  "(この指定を外さないでください)。\n");
console.log("wrote   README.md");
